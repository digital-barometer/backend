import json
from collections.abc import Mapping, Sequence

from langchain_core.prompts import PromptTemplate

SENTIMENT_SYSTEM_PROMPT = (
    "Ты классифицируешь тональность русскоязычных и англоязычных текстов "
    "для цифрового барометра по конкретной теме/области. "
    "Оценивай не общий эмоциональный окрас фразы, а влияние текста на репутацию, "
    "восприятие или состояние указанной темы. "
    "Работай только с переданными текстами и темой анализа. "
    "positive: текст сообщает о пользе, росте, улучшении, успехе, доверии, "
    "удовлетворенности, рекомендации, решении проблемы или сильной поддержке темы. "
    "negative: текст сообщает о вреде, падении, сбое, риске, потере, жалобе, "
    "скандале, конфликте, недоверии, разочаровании, бойкоте или ухудшении для темы. "
    "neutral: текст в основном фактологический, справочный, процедурный, "
    "вопросительный или описательный и не показывает явной пользы/вреда для темы. "
    "unknown: текста недостаточно, он не относится к теме или смысл нельзя надежно определить; "
    "не используй unknown для короткого, но понятного новостного заголовка по теме. "
    "Если есть смешанные сигналы, выбери доминирующий эффект для темы; neutral ставь только "
    "когда позитив и негатив сбалансированы или оценки нет. "
    "Ограничения, запреты, ДТП, травмы, наезды, жалобы, кражи, взломы и штрафы "
    "считай негативом для темы, если это не явная хорошая новость об устранении проблемы. "
    "Новые парковки, запуск сервиса, расширение доступности, рост спроса, новые полезные "
    "функции и устранение проблемы считай позитивом. "
    "Появление правил, обзоры, справки и нейтральные новости о наличии сервиса без оценки "
    "считай neutral. "
    "Учитывай синонимы и распространенные сокращения темы: например для электросамокатов "
    "это самокаты, СИМ и средства индивидуальной мобильности. "
    "Учитывай отрицания, сарказм, сравнения и контекст отрасли: например рост жалоб "
    "негативен, а рост спроса позитивен. "
    "Для каждого элемента верни index, sentiment, sentiment_score, emotion. "
    "sentiment только: positive, neutral, negative, unknown. "
    "sentiment_score число от -1 до 1: около -1 сильный негатив, около 0 нейтрально "
    "или неизвестно, около 1 сильный позитив. "
    "emotion только: радость, раздражение, страх, доверие, удивление, злость, неопределено."
)

METRICS_SYSTEM_PROMPT = (
    "Ты аналитический модуль цифрового барометра. "
    "Формируй вывод только на основе переданного JSON-контекста. "
    "barometer_label только: негативная тенденция, нейтральная, позитивная. "
    "summary_short одно короткое предложение. "
    "summary_detailed 1-2 предложения. "
    "Не выдумывай числа: используй только входные counts и trend. "
    "Если sentiment_counts содержит unknown, учитывай это в выводе; при большой доле unknown "
    "не делай уверенный вывод о настроении всей выборки. "
    "trend описывает только динамику поискового интереса Google Trends, а не тональность, "
    "не количество публикаций и не динамику обсуждений. "
    "Если trend.has_data=true, формулируй это как рост/снижение/стабильность поискового "
    "интереса; не называй снижение trend негативной динамикой обсуждения или ухудшением "
    "отношения к теме. "
    "Если trend.has_data=false или trend.points_count=0, пиши, что данных по тренду нет; "
    "не называй это нулевым, стабильным или отсутствующим изменением тренда."
)

SENTIMENT_USER_PROMPT = PromptTemplate.from_template(
    "Тема анализа: {topic_name}\n\n"
    "Проанализируй тональность каждого текста из массива JSON относительно этой темы. "
    "Сохрани исходный index в ответе для каждого элемента. "
    "Верни строго JSON-объект вида "
    '{{"items":[{{"index":0,"sentiment":"negative","sentiment_score":-0.7,'
    '"emotion":"страх"}}]}} без markdown и пояснений.\n\n'
    "Тексты:\n{items_json}"
)

METRICS_USER_PROMPT = PromptTemplate.from_template(
    "Сформируй аналитическую сводку по теме на основе JSON-контекста. "
    "Не добавляй факты, которых нет во входных данных. "
    "Отделяй тональность упоминаний от поискового интереса: sentiment_counts отвечает "
    "за настрой публикаций, trend отвечает только за Google Trends. "
    "Верни строго JSON-объект вида "
    '{{"barometer_label":"негативная тенденция","summary_short":"...",'
    '"summary_detailed":"..."}} без markdown и пояснений.\n\n'
    "Контекст:\n{context_json}"
)


def build_sentiment_user_prompt(
    topic_name: str,
    items: Sequence[Mapping[str, object]],
) -> str:
    return SENTIMENT_USER_PROMPT.format(topic_name=topic_name, items_json=_to_json(items))


def build_metrics_user_prompt(context: Mapping[str, object]) -> str:
    return METRICS_USER_PROMPT.format(context_json=_to_json(context))


def _to_json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, default=str, indent=2)
